/**
 * Dynamic Google Translate Element Loader & Activator
 */
declare global {
 interface Window {
 google?: any;
 googleTranslateElementInit?: () => void;
 }
}

export function initGoogleTranslate(targetLang: Language = 'hi', enabled: boolean = true): void {
 if (!enabled || targetLang === 'en') {
 // If disabled or English, reset Google Translate cookie if present
 document.cookie = 'googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;';
 const gtFrame = document.querySelector('.goog-te-banner-frame');
 if (gtFrame && gtFrame.parentNode) {
 gtFrame.parentNode.removeChild(gtFrame);
 }
 return;
 }

 const langCode = targetLang === 'hi' ? 'hi' : targetLang === 'gu' ? 'gu' : 'en';
 document.cookie = `googtrans=/en/${langCode}; path=/;`;

 if (!document.getElementById('google-translate-script')) {
 window.googleTranslateElementInit = function () {
 if (window.google && window.google.translate) {
 new window.google.translate.TranslateElement(
 {
 pageLanguage: 'en',
 includedLanguages: 'en,hi,gu',
 autoDisplay: false
 },
 'google_translate_element'
 );
 }
 };
 const s = document.createElement('script');
 s.id = 'google-translate-script';
 s.src = 'https://translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
 document.head.appendChild(s);
 } else {
 // Re-trigger language change
 const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
 if (select) {
 select.value = langCode;
 select.dispatchEvent(new Event('change'));
 }
 }
}
